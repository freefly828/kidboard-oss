/** 按日期选当日古诗（同一天各端一致；按天数轮换，覆盖全部诗目后循环） */
export function poemOfDay(date: string): Poem {
  const days = Math.floor(Date.parse(`${date}T00:00:00Z`) / 86_400_000);
  const index = ((days % POEMS.length) + POEMS.length) % POEMS.length;
  return POEMS[index]!;
}
